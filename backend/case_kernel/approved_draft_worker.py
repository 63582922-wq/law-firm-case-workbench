def create_docx_draft(draft: ApprovedDraft) -> DraftArtifact:
    _validate_draft(draft)
    document = Document()
    _configure_domestic_docx(document)
    document.core_properties.title = draft.title
    document.core_properties.subject = "国内律师内部复核候选（非正式文书）"
    document.core_properties.category = "律师复核候选"
    document.core_properties.identifier = draft.approval_hash
    document.core_properties.author = "律所案件AI工作台"
    document.core_properties.last_modified_by = "律所案件AI工作台"
    # Office packages require core timestamps.  Use a stable packaging epoch;
    # the authoritative generation time remains the audited system receipt.
    document.core_properties.created = _OOXML_CORE_DATETIME
    document.core_properties.modified = _OOXML_CORE_DATETIME
    document.add_heading(draft.title, level=0)
    document.add_paragraph(
        f"{_CANDIDATE_STATUS}｜{_RECEIPT_TIME_NOTE}｜版本摘要 {draft.approval_hash[:12]}",
        style=_REVIEW_NOTE_STYLE,
    )
    for section in draft.sections:
        document.add_heading(section.heading, level=_heading_level(section.heading))
        for paragraph in section.paragraphs:
            document.add_paragraph(paragraph)
        document.add_paragraph(
            "来源注记：" + "；".join(section.source_refs),
            style=_SOURCE_NOTE_STYLE,
        )
    destination = BytesIO()
    document.save(destination)
    return _artifact(
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        _deterministic_ooxml(
            destination.getvalue(),
            docx_fonts=(
                _DOCX_TITLE_FONT,
                _DOCX_HEADING_FONT,
                _DOCX_SECONDARY_HEADING_FONT,
                _DOCX_BODY_FONT,
                _DOCX_NOTE_FONT,
            ),
        ),
    )


def create_xlsx_ledger(
    *,
    approval_hash: str,
    sheet_name: str,
    columns: tuple[str, ...],
    rows: Iterable[tuple[str | int | float | Decimal | date | datetime | None, ...]],
) -> DraftArtifact:
    _validate_approval_hash(approval_hash)
    if (
        not sheet_name.strip()
        or len(sheet_name) > 31
        or any(char in sheet_name for char in "[]:*?/\\")
        or _UNSAFE_XML_TEXT_RE.search(sheet_name)
    ):
        raise ApprovedDraftBlocked("ledger sheet name is invalid")
    if not 1 <= len(columns) <= _MAX_COLUMNS or any(
        not value.strip() or len(value) > 160 or _UNSAFE_XML_TEXT_RE.search(value)
        for value in columns
    ):
        raise ApprovedDraftBlocked("ledger columns are invalid")
    validated_rows: list[
        tuple[str | int | float | Decimal | date | datetime | None, ...]
    ] = []
    row_count = 0
    text_characters = sum(len(column) for column in columns)
    for row in rows:
        if len(row) != len(columns):
            raise ApprovedDraftBlocked("ledger row width does not match columns")
        values = tuple(_safe_cell_value(value) for value in row)
        text_characters += sum(len(value) for value in values if isinstance(value, str))
        if text_characters > _MAX_LEDGER_TEXT_CHARS:
            raise ApprovedDraftBlocked("ledger text exceeds the supported boundary")
        validated_rows.append(values)
        row_count += 1
        if row_count > _MAX_ROWS:
            raise ApprovedDraftBlocked("ledger row limit exceeded")
    if row_count == 0:
        raise ApprovedDraftBlocked("ledger requires at least one approved row")
    clean_sheet_name = sheet_name.strip()
    workbook = Workbook(write_only=True)
    _configure_domestic_workbook_metadata(workbook, clean_sheet_name, approval_hash)
    styles = _register_domestic_xlsx_styles(workbook)
    sheet = workbook.create_sheet(title=clean_sheet_name)
    _configure_domestic_ledger_sheet(
        sheet,
        columns=columns,
        rows=validated_rows,
        approval_hash=approval_hash,
    )
    last_column = get_column_letter(len(columns))
    if len(columns) > 1:
        sheet.merged_cells.add(f"A1:{last_column}1")
        sheet.merged_cells.add(f"A2:{last_column}2")
    sheet.append([_xlsx_cell(sheet, clean_sheet_name, styles["title"])])
    sheet.append([
        _xlsx_cell(
            sheet,
            f"{_CANDIDATE_STATUS}｜{_RECEIPT_TIME_NOTE}｜版本摘要 {approval_hash[:12]}",
            styles["notice"],
        )
    ])
    sheet.append([_xlsx_cell(sheet, value, styles["header"]) for value in columns])
    for row in validated_rows:
        sheet.append(
            [
                _xlsx_cell(sheet, value, _xlsx_data_style(styles, columns[index], value))
                for index, value in enumerate(row)
            ]
        )
    destination = BytesIO()
    workbook.save(destination)
    return _artifact(
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        _deterministic_ooxml(destination.getvalue()),
    )


def create_pdf_draft(draft: ApprovedDraft) -> DraftArtifact:
    _validate_draft(draft)
    _register_domestic_pdf_fonts()
    destination = BytesIO()
    document = canvas.Canvas(
        destination,
        pagesize=A4,
        pageCompression=1,
        invariant=1,
        # ReportLab otherwise creates an unused, unembedded Helvetica resource.
        initialFontName=_PDF_TEXT_FONT,
    )
    document.setTitle(draft.title)
    document.setAuthor("律所案件AI工作台")
    document.setCreator("律所案件AI工作台")
    document.setSubject("国内律师内部复核候选（非正式文书）")
    document.setKeywords(f"律师复核候选 candidate_sha256:{draft.approval_hash}")
    writer = _DomesticPdfWriter(document)
    width, height = A4
    content_width = width - writer.left_margin - writer.right_margin
    y = height - writer.top_margin
    document.setFillColorRGB(0, 0, 0)
    for title_line in _wrap(
        draft.title,
        content_width,
        18,
        font_name=_PDF_HEADING_FONT,
    ):
        y = writer.ensure_y(y, minimum=writer.bottom_margin + 22)
        _draw_pdf_text(document, writer.left_margin + content_width / 2, y, title_line, 18, centered=True, bold=True)
        y -= 24
    document.setFillColor(Color(0.32, 0.32, 0.32))
    review_line = f"{_CANDIDATE_STATUS}｜{_RECEIPT_TIME_NOTE}｜版本摘要 {draft.approval_hash[:12]}"
    for line in _wrap(
        review_line,
        content_width,
        10,
        font_name=_PDF_SECONDARY_FONT,
    ):
        y = writer.ensure_y(y, minimum=writer.bottom_margin + 18)
        _draw_pdf_text(
            document,
            writer.left_margin + content_width / 2,
            y,
            line,
            10,
            centered=True,
            font_name=_PDF_SECONDARY_FONT,
        )
        y -= 16
    document.setFillColorRGB(0, 0, 0)
    y -= 8
    for section in draft.sections:
        heading_level = _heading_level(section.heading)
        heading_size = 14 if heading_level == 1 else 12
        heading_lines = _wrap(
            section.heading,
            content_width,
            heading_size,
            font_name=(
                _PDF_SECONDARY_FONT
                if heading_level == 2
                else _PDF_HEADING_FONT
            ),
        )
        y = writer.ensure_y(y, minimum=writer.bottom_margin + 44)
        for line in heading_lines:
            _draw_pdf_text(
                document,
                writer.left_margin,
                y,
                line,
                heading_size,
                bold=heading_level != 2,
                font_name=(
                    _PDF_SECONDARY_FONT
                    if heading_level == 2
                    else _PDF_HEADING_FONT
                ),
            )
            y -= 22
        for paragraph in section.paragraphs:
            paragraph_lines = _wrap_first_line(paragraph, content_width, 12, 24)
            y = writer.keep_short_block_together(
                y,
                line_count=len(paragraph_lines),
                line_height=22,
                minimum=writer.bottom_margin + 22,
            )
            for index, line in enumerate(paragraph_lines):
                y = writer.ensure_y(y, minimum=writer.bottom_margin + 22)
                x = writer.left_margin + (24 if index == 0 else 0)
                _draw_pdf_text(document, x, y, line, 12)
                y -= 22
            y -= 2
        document.setFillColor(Color(0.35, 0.35, 0.35))
        for line in _wrap(
            "来源注记：" + "；".join(section.source_refs),
            content_width,
            10,
            font_name=_PDF_SECONDARY_FONT,
        ):
            y = writer.ensure_y(y, minimum=writer.bottom_margin + 18)
            _draw_pdf_text(
                document,
                writer.left_margin,
                y,
                line,
                10,
                font_name=_PDF_SECONDARY_FONT,
            )
            y -= 16
        document.setFillColorRGB(0, 0, 0)
        y -= 8
    writer.finish()
    return _artifact("application/pdf", destination.getvalue())


def validate_approved_draft(draft: ApprovedDraft) -> None:
    """Validate a bounded approved snapshot for controlled downstream workers."""

    _validate_draft(draft)


def _validate_draft(draft: ApprovedDraft) -> None:
    _validate_approval_hash(draft.approval_hash)
    if (
        not draft.title.strip()
        or len(draft.title) > 240
        or _UNSAFE_XML_TEXT_RE.search(draft.title)
    ):
        raise ApprovedDraftBlocked("draft title is invalid")
    if not 1 <= len(draft.sections) <= _MAX_SECTIONS:
        raise ApprovedDraftBlocked("draft section count is invalid")
    paragraphs = 0
    characters = len(draft.title)
    for section in draft.sections:
        if (
            not section.heading.strip()
            or len(section.heading) > 240
            or _UNSAFE_XML_TEXT_RE.search(section.heading)
            or not section.source_refs
        ):
            raise ApprovedDraftBlocked("each section requires a heading and approved source references")
        for source_ref in section.source_refs:
            if (
                not source_ref.strip()
                or len(source_ref) > 240
                or _UNSAFE_XML_TEXT_RE.search(source_ref)
            ):
                raise ApprovedDraftBlocked("draft source reference is invalid")
        for paragraph in section.paragraphs:
            if not paragraph.strip() or _UNSAFE_XML_TEXT_RE.search(paragraph):
                raise ApprovedDraftBlocked("draft paragraph is blank")
            paragraphs += 1
            characters += len(paragraph)
    if paragraphs < 1 or paragraphs > _MAX_PARAGRAPHS or characters > _MAX_TEXT_CHARS:
        raise ApprovedDraftBlocked("draft content exceeds the supported boundary")


def _validate_approval_hash(value: str) -> None:
    if not _SHA256_RE.fullmatch(value):
        raise ApprovedDraftBlocked("draft requires a lawyer approval SHA-256")


def _register_domestic_pdf_fonts() -> None:
    """Register embedded Simplified-Chinese fonts or fail closed.

    Managed Linux runtimes install the three pinned Debian font packages used
    below.  The macOS pair is only a local development-preview equivalent;
    neither path falls back to ReportLab's unembedded built-in CJK font
    references.  Domestic-format release acceptance is performed in the
    managed Linux runtime, where the distinct UKai face is present.
    """

    required_names = {_PDF_TEXT_FONT, _PDF_HEADING_FONT, _PDF_SECONDARY_FONT}
    registered = set(pdfmetrics.getRegisteredFontNames())
    if required_names.issubset(registered):
        return
    with _PDF_FONT_REGISTRATION_LOCK:
        registered = set(pdfmetrics.getRegisteredFontNames())
        if required_names.issubset(registered):
            return
        if (
            _MANAGED_PDF_BODY_FONT.is_file()
            and _MANAGED_PDF_HEADING_FONT.is_file()
            and _MANAGED_PDF_SECONDARY_FONT.is_file()
        ):
            body_path = _MANAGED_PDF_BODY_FONT
            body_index = 0
            heading_path = _MANAGED_PDF_HEADING_FONT
            heading_index = 0
            secondary_path = _MANAGED_PDF_SECONDARY_FONT
            secondary_index = 0
        elif (
            sys.platform == "darwin"
            and _MACOS_PDF_BODY_FONT.is_file()
            and _MACOS_PDF_HEADING_FONT.is_file()
        ):
            body_path = _MACOS_PDF_BODY_FONT
            body_index = 3  # STSongti-SC-Light
            heading_path = _MACOS_PDF_HEADING_FONT
            heading_index = 1  # STHeitiSC-Medium
            # macOS does not expose a stable embeddable Kaiti path.  Keep local
            # development portable with Songti; managed Linux uses UKai above.
            secondary_path = _MACOS_PDF_BODY_FONT
            secondary_index = 3
        else:
            raise ApprovedDraftBlocked(
                "embedded Simplified-Chinese PDF fonts are unavailable"
            )
        try:
            pdfmetrics.registerFont(
                TTFont(_PDF_TEXT_FONT, str(body_path), subfontIndex=body_index)
            )
            pdfmetrics.registerFont(
                TTFont(
                    _PDF_HEADING_FONT,
                    str(heading_path),
                    subfontIndex=heading_index,
                )
            )
            pdfmetrics.registerFont(
                TTFont(
                    _PDF_SECONDARY_FONT,
                    str(secondary_path),
                    subfontIndex=secondary_index,
                )
            )
        except Exception as exc:
            raise ApprovedDraftBlocked(
                "embedded Simplified-Chinese PDF fonts could not be loaded"
            ) from exc


def _heading_level(value: str) -> int:
    """Map only explicit Chinese legal-document numbering to visual levels."""

    prefix = value.lstrip()
    if re.match(r"^（[一二三四五六七八九十百]+）", prefix):
        return 2
    if re.match(r"^\d+(?:\.|、)", prefix):
        return 3
    if re.match(r"^[（(]\d+[）)]", prefix):
        return 4
    return 1


