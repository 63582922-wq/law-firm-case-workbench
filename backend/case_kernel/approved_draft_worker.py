def _set_docx_style_font(style: object, east_asia_font: str, size: float, *, bold: bool = False) -> None:
    # Keep every run in a CJK-capable family.  python-docx does not emit a
    # per-run East Asian language hint, and headless LibreOffice can therefore
    # classify Chinese glyphs as hAnsi.  If ascii/hAnsi points at Times New
    # Roman those glyphs render as empty squares even though w:eastAsia names a
    # valid Chinese face.  Using the selected legal-document face for all four
    # script slots makes Word and the independent renderer agree while keeping
    # Latin numerals and identifiers readable.
    style.font.name = east_asia_font
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.italic = False
    style.font.color.rgb = RGBColor(0x00, 0x00, 0x00)
    run_properties = style.element.get_or_add_rPr()
    font_map = run_properties.find(qn("w:rFonts"))
    if font_map is None:
        font_map = OxmlElement("w:rFonts")
