def _column_role(column: str) -> str:
    normalized = column.strip().casefold()
    if any(token in normalized for token in ("日期精度", "date_precision", "precision")):
        return "precision"
    if any(token in normalized for token in ("日期", "时间", "date", "time")):
        return "date"
    if any(token in normalized for token in ("金额", "本金", "利息", "余额", "合计", "amount", "total")):
        return "amount"
    if any(
        token in normalized
        for token in ("序号", "顺序", "数量", "笔数", "sequence", "count")
    ):
        return "integer"
    if any(token in normalized for token in ("来源", "证据", "source")):
        return "source"
    if any(token in normalized for token in ("币种", "currency")):
        return "currency"
    if any(token in normalized for token in ("方向", "direction")):
        return "direction"
    if any(token in normalized for token in ("付款方", "收款方", "主体", "payer", "payee", "party")):
        return "party"
    if any(token in normalized for token in ("渠道", "channel")):
        return "channel"
    if any(token in normalized for token in ("流水号", "参考号", "reference")):
        return "reference"
    if any(token in normalized for token in ("交易性质", "款项性质", "nature")):
        return "nature"
    return "text"


def _estimated_wrapped_lines(value: object, width: float) -> int:
    if value is None:
        return 1
    rendered = value.isoformat() if isinstance(value, (date, datetime)) else str(value)
    usable_width = max(1, int(width) - 1)
    return max(
        1,
        sum(
            max(1, ceil(_display_width(segment, limit=None) / usable_width))
            for segment in rendered.replace("\r\n", "\n").replace("\r", "\n").split("\n")
        ),
    )


def _display_width(value: object, *, limit: int | None = 80) -> int:
    if value is None:
        return 0
    rendered = value.isoformat() if isinstance(value, (date, datetime)) else str(value)
    width = sum(
        2 if east_asian_width(character) in {"W", "F", "A"} else 1
        for character in rendered
    )
    return min(limit, width) if limit is not None else width


def _safe_cell_value(
    value: str | int | float | Decimal | date | datetime | None,
) -> str | int | float | Decimal | date | datetime | None:
    if value is None:
        return None
    if isinstance(value, bool):
        raise ApprovedDraftBlocked("ledger cell value is invalid")
    if isinstance(value, float):
        if not isfinite(value):
            raise ApprovedDraftBlocked("ledger cell value is invalid")
        return value
    if isinstance(value, Decimal):
        if not value.is_finite():
            raise ApprovedDraftBlocked("ledger cell value is invalid")
        return value
    if isinstance(value, int):
        return value
    if isinstance(value, datetime):
        if value.tzinfo is not None and value.utcoffset() is not None:
            raise ApprovedDraftBlocked("ledger datetime must not contain a timezone")
        return value
    if isinstance(value, date):
        return value
    if not isinstance(value, str) or len(value) > 10_000 or _UNSAFE_XML_TEXT_RE.search(value):
        raise ApprovedDraftBlocked("ledger cell value is invalid")
    candidate = value.lstrip(" \t\r\n")
    return f"'{value}" if candidate.startswith(("=", "+", "-", "@")) else value


class _DomesticPdfWriter:
    def __init__(self, document: canvas.Canvas) -> None:
        self.document = document
        self.left_margin = 30 * mm
        self.right_margin = 25 * mm
        self.top_margin = 30 * mm
        self.bottom_margin = 25 * mm
        self.page_number = 1
        self._draw_header()

    def ensure_y(self, y: float, *, minimum: float) -> float:
        if y >= minimum:
            return y
        return self._start_new_page()

    def keep_short_block_together(
        self,
        y: float,
        *,
        line_count: int,
        line_height: float,
        minimum: float,
    ) -> float:
        """Move a short paragraph intact instead of leaving an orphan line.

        A block longer than a fresh page is still allowed to paginate normally.
        This keeps ordinary legal-analysis paragraphs, dates, and decision
        options from leaving only a closing bracket or punctuation mark at the
        top of the next page.
        """

        if line_count <= 1:
            return y
        fresh_y = A4[1] - self.top_margin
        last_baseline_offset = (line_count - 1) * line_height
        fits_fresh_page = fresh_y - last_baseline_offset >= minimum
        fits_current_page = y - last_baseline_offset >= minimum
        if fits_fresh_page and not fits_current_page:
            return self._start_new_page()
        return y

    def _start_new_page(self) -> float:
        self._draw_footer()
        self.document.showPage()
        self.page_number += 1
        self._draw_header()
        return A4[1] - self.top_margin

    def finish(self) -> None:
        self._draw_footer()
        self.document.save()

    def _draw_header(self) -> None:
        self.document.saveState()
        self.document.setFillColor(Color(0.35, 0.35, 0.35))
        self.document.setFont(_PDF_TEXT_FONT, 9)
        self.document.drawCentredString(A4[0] / 2, A4[1] - 15 * mm, "律师复核候选｜待律师终审")
        self.document.restoreState()

    def _draw_footer(self) -> None:
        self.document.saveState()
        self.document.setFillColor(Color(0.35, 0.35, 0.35))
        self.document.setFont(_PDF_TEXT_FONT, 9)
        self.document.drawCentredString(
            A4[0] / 2,
            17.5 * mm,
            f"非正式文书｜律师复核候选｜第 {self.page_number} 页",
        )
        self.document.restoreState()


def _draw_pdf_text(
    document: canvas.Canvas,
    x: float,
    y: float,
    value: str,
    size: int,
    *,
    centered: bool = False,
    bold: bool = False,
    font_name: str | None = None,
) -> None:
    preferred_font = font_name or (_PDF_HEADING_FONT if bold else _PDF_TEXT_FONT)
    document.saveState()
    if centered:
        x -= _pdf_string_width(value, preferred_font, size) / 2
    text = document.beginText(x, y)
    for font_name, run in _pdf_text_runs(value, preferred_font):
        text.setFont(font_name, size)
        text.textOut(run)
    document.drawText(text)
    document.restoreState()


def _wrap(
    value: str,
    width: float,
    size: int,
    *,
    font_name: str = _PDF_TEXT_FONT,
) -> tuple[str, ...]:
    return _wrap_first_line(value, width, size, 0, font_name=font_name)


def _wrap_first_line(
    value: str,
    width: float,
    size: int,
    first_line_indent: float,
    *,
    font_name: str = _PDF_TEXT_FONT,
) -> tuple[str, ...]:
    lines: list[str] = []
    current = ""
    first_output_line = True
    normalized = value.replace("\t", "    ").replace("\r\n", "\n").replace("\r", "\n")
    for unit in _pdf_wrap_units(normalized):
        if unit == "\n":
            lines.append(current.rstrip())
            current = ""
            first_output_line = False
            continue
        available_width = width - (first_line_indent if first_output_line and not lines else 0)
        if not current and unit.isspace():
            continue
        candidate = current + unit
        if _pdf_string_width(candidate, font_name, size) <= available_width:
            current = candidate
            continue

        # Closing punctuation belongs to the preceding Chinese clause.  A
        # one-glyph optical overhang is preferable to starting a page or line
        # with a detached bracket or full stop.
        if current and unit in "，。；：！？、）》】〕〉」』）]};:,.!?%":
            current += unit
            continue

        carry = ""
        if current and current[-1] in "（《【〔〈「『([{" :
            carry = current[-1]
            current = current[:-1]
        if current.rstrip():
            lines.append(current.rstrip())
            first_output_line = False
        current = carry

        if unit.isspace():
            continue
        available_width = width
        candidate = current + unit
        if _pdf_string_width(candidate, font_name, size) <= available_width:
            current = candidate
            continue

        # Exceptionally long machine identifiers and official-source URLs may
        # exceed a whole legal-document line.  Split only those oversized
        # units; ordinary dates, amounts, scenario IDs and authority IDs stay
        # intact.
        oversized = candidate
        current = ""
        while oversized:
            prefix = ""
            split_at = 0
            for index, char in enumerate(oversized, start=1):
                if prefix and _pdf_string_width(
                    prefix + char, font_name, size
                ) > available_width:
                    break
                prefix += char
                split_at = index
            if not prefix:
                prefix = oversized[0]
                split_at = 1
            oversized = oversized[split_at:]
            if oversized:
                lines.append(prefix)
                first_output_line = False
            else:
                current = prefix
    if current or not lines:
        lines.append(current.rstrip())
    return tuple(lines)


def _pdf_wrap_units(value: str) -> tuple[str, ...]:
    """Tokenize only machine-like text; Chinese prose remains breakable.

    Character-by-character wrapping made dates, amounts, IDs and L1/L2 labels
    appear as different facts across two lines.  Treat contiguous ASCII
    machine tokens and RMB amounts as one unit while preserving normal Chinese
    line breaking.
    """

    units: list[str] = []
    index = 0
    machine_characters = frozenset("._:/%_-#?&=+@")
    while index < len(value):
        char = value[index]
        if char == "\n":
            units.append(char)
            index += 1
            continue
        if char.isspace():
            end = index + 1
            while end < len(value) and value[end].isspace() and value[end] != "\n":
                end += 1
            units.append(value[index:end])
            index = end
            continue
        if char == "￥" and index + 1 < len(value) and value[index + 1].isdigit():
            end = index + 2
            while end < len(value) and (
                value[end].isdigit() or value[end] in ",.%"
            ):
                end += 1
            units.append(value[index:end])
            index = end
            continue
        if char.isascii() and (char.isalnum() or char in "#@"):
            end = index + 1
            while end < len(value):
                candidate = value[end]
                if not candidate.isascii() or not (
                    candidate.isalnum() or candidate in machine_characters
                ):
                    break
                end += 1
            units.append(value[index:end])
            index = end
            continue
        units.append(char)
        index += 1
    return tuple(units)


def _pdf_string_width(value: str, preferred_font: str, size: int) -> float:
    return sum(
        pdfmetrics.stringWidth(run, font_name, size)
        for font_name, run in _pdf_text_runs(value, preferred_font)
    )


def _pdf_text_runs(value: str, preferred_font: str) -> tuple[tuple[str, str], ...]:
    candidate_fonts = (preferred_font,) + tuple(
        font_name
        for font_name in (
            _PDF_TEXT_FONT,
            _PDF_HEADING_FONT,
            _PDF_SECONDARY_FONT,
        )
        if font_name != preferred_font
    )
    runs: list[tuple[str, str]] = []
    current_font = ""
    current_text = ""
    for character in value:
        codepoint = ord(character)
        unicode_category = category(character)
        # ReportLab 4.x writes an invalid one-code-unit ToUnicode mapping for
        # astral characters even when a managed font contains the glyph.  It
        # also draws several combining/format controls as visible boxes or
        # separate glyphs.  Legal names and quoted source text must never be
        # silently changed, detached or made unsearchable, so the direct-PDF
        # fallback rejects these inputs.  The Office-rendered DOCX/PDF path is
        # the governed route for text that needs shaping or astral coverage.
        if (
            codepoint > 0xFFFF
            or codepoint in {0xFFFC, 0xFFFD}
            or unicode_category.startswith("M")
            or unicode_category in {"Cc", "Cf", "Cs", "Co", "Cn"}
        ):
            raise ApprovedDraftBlocked(
                "embedded PDF renderer cannot safely preserve "
                f"U+{codepoint:04X} (Unicode category {unicode_category})"
            )
        font_name = next(
            (
                candidate
                for candidate in candidate_fonts
                if _pdf_font_has_visible_glyph(candidate, character)
            ),
            None,
        )
        if font_name is None:
            raise ApprovedDraftBlocked(
                f"embedded PDF fonts cannot render U+{codepoint:04X}"
            )
        if font_name == current_font:
            current_text += character
            continue
        if current_text:
            runs.append((current_font, current_text))
        current_font = font_name
        current_text = character
    if current_text:
        runs.append((current_font, current_text))
    return tuple(runs)


def _pdf_font_has_visible_glyph(font_name: str, character: str) -> bool:
    """Reject cmap entries whose TrueType glyph has no drawable outline.

    Some managed CJK fonts advertise a character in their cmap/advance table
    but leave its glyph data empty.  ReportLab then advances one full cell and
    silently prints a blank.  Ordinary Unicode spaces are the only intentional
    empty glyphs accepted here; every other character must have real glyph
    data so the caller can fall through to the next managed font.
    """

    codepoint = ord(character)
    face = pdfmetrics.getFont(font_name).face
    if codepoint not in face.charWidths:
        return False
    glyph_index = face.charToGlyph.get(codepoint)
    if glyph_index is None:
        return False
    if category(character) == "Zs":
        return True
    glyph_positions = face.glyphPos
    return (
        glyph_index >= 0
        and glyph_index + 1 < len(glyph_positions)
        and glyph_positions[glyph_index + 1] > glyph_positions[glyph_index]
    )


def _deterministic_ooxml(content: bytes, *, docx_fonts: tuple[str, ...] = ()) -> bytes:
    """Repack Office ZIPs with stable member order/timestamps for audit hashes."""

    source = BytesIO(content)
    destination = BytesIO()
    with ZipFile(source, "r") as archive, ZipFile(
        destination,
        "w",
        compression=ZIP_DEFLATED,
        compresslevel=9,
    ) as output:
        for name in sorted(archive.namelist()):
            item = ZipInfo(name, date_time=_OOXML_TIMESTAMP)
            item.compress_type = ZIP_DEFLATED
            item.create_system = 0
            item.external_attr = 0
            item.extra = b""
            item.comment = b""
            member = archive.read(name)
            if name == "word/fontTable.xml" and docx_fonts:
                member = _augment_docx_font_table(member, docx_fonts)
            if name == "docProps/core.xml":
                member = _normalize_ooxml_core_properties(member)
            output.writestr(item, member, compress_type=ZIP_DEFLATED, compresslevel=9)
    return destination.getvalue()


def _normalize_ooxml_core_properties(content: bytes) -> bytes:
    """Remove library save-time drift from otherwise identical Office files."""

    normalized = content
    for field in (b"created", b"modified"):
        pattern = re.compile(
            rb"(<dcterms:"
            + field
            + rb"\b[^>]*>)[^<]*(</dcterms:"
            + field
            + rb">)"
        )
        normalized, count = pattern.subn(
            rb"\g<1>" + _OOXML_CORE_DATETIME_TEXT + rb"\g<2>",
            normalized,
            count=1,
        )
        if count != 1:
            raise ApprovedDraftBlocked(
                "Office core properties lack a deterministic timestamp"
            )
    return normalized


def _augment_docx_font_table(content: bytes, fonts: tuple[str, ...]) -> bytes:
    """Declare every portable CJK face and its macOS alternative.

    python-docx writes style references but omits non-template faces from
    ``fontTable.xml``.  LibreOffice then treats the missing east-Asian family
    as unavailable and emits empty-square glyphs even when the font is
    installed.  Explicit declarations plus ``w:altName`` make the editable
    DOCX portable without embedding or redistributing proprietary font files.
    Managed Linux still resolves the primary domestic names through the
    audited fontconfig alias file.
    """

    closing = b"</w:fonts>"
    if closing not in content:
        raise ApprovedDraftBlocked("DOCX font table is malformed")
    entries: list[str] = []
    for font in dict.fromkeys(fonts):
        encoded_name = f'w:name="{xml_escape(font, quote=True)}"'.encode("utf-8")
        if encoded_name in content:
            continue
        family = "swiss" if font in {_DOCX_TITLE_FONT, _DOCX_HEADING_FONT} else "roman"
        alternate = _DOCX_FONT_ALTERNATES.get(font)
        alternate_xml = (
            f'<w:altName w:val="{xml_escape(alternate, quote=True)}"/>'
            if alternate is not None
            else ""
        )
        entries.append(
            f'<w:font w:name="{xml_escape(font, quote=True)}">'
            + alternate_xml
            + '<w:charset w:val="86"/>'
            + f'<w:family w:val="{family}"/>'
            + '<w:pitch w:val="variable"/>'
            + '</w:font>'
        )
    if not entries:
        return content
    return content.replace(closing, "".join(entries).encode("utf-8") + closing, 1)


def _artifact(media_type: str, content: bytes) -> DraftArtifact:
    if not content:
        raise ApprovedDraftBlocked("draft generator returned an empty artifact")
    return DraftArtifact(media_type, content, sha256(content).hexdigest())
